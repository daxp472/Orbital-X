/**
 * Evaluates whether a user request is direct (localized) or complex (multi-step/subsystem).
 * Following Gravitas:
 * - Direct: Localized queries, typos, simple explanations, single inspections.
 * - Complex: Multi-step features, refactoring, building whole subsystems, migrations, explicit /plan.
 */
export function isComplexRequest(prompt) {
  if (!prompt || typeof prompt !== 'string') return false;
  const p = prompt.trim();
  const pLower = p.toLowerCase();

  // Explicit plan command
  if (pLower.startsWith('/plan')) return true;

  // Question/inspection patterns that are strictly simple
  const simpleStarts = [
    'what is', 'what does', 'explain', 'how do i', 'how to',
    'read ', 'view ', 'show ', 'where is', 'find ', 'search ',
    'git status', 'git diff', 'echo ', 'help', 'list '
  ];
  if (simpleStarts.some(prefix => pLower.startsWith(prefix)) && p.length < 90 && !p.includes('\n')) {
    return false;
  }

  // Multi-step complex indicators
  const complexKeywords = [
    'implement', 'refactor', 'orchestrat', 'overhaul', 'build',
    'migrate', 'architecture', 'subsystem', 'full stack', 'end to end',
    'create module', 'add feature', 'upgrade', 'restructure'
  ];
  const hasComplexKeyword = complexKeywords.some(kw => pLower.includes(kw));

  // Multiple requirements / numbered lists / bullet points
  const hasMultipleSteps = (p.match(/\d+[\.\)]\s/g) || []).length >= 2 ||
                           (p.match(/[-*•]\s+/g) || []).length >= 2 ||
                           p.includes(' then ') || p.includes(' and also ');

  // Substantial prompt with action verbs
  const isSubstantial = p.length > 120 && (hasComplexKeyword || hasMultipleSteps);

  return hasComplexKeyword || hasMultipleSteps || isSubstantial;
}

/**
 * Creates a repository-aware structured implementation plan before code mutation.
 *
 * The breakdown is generated by the active model from the actual request and
 * repository context. The previous fixed four-task template is kept only as a
 * clearly-labelled fallback for when the model is unreachable or returns
 * unparseable output.
 */
export async function createPlan(prompt, projectStructure = null, inspectedFiles = []) {
  const cleanPrompt = prompt.replace(/^\/plan\s*/i, '').trim() || 'Workspace Enhancement';
  const planId = 'plan_' + Date.now();

  const configs = projectStructure?.config_files || [];
  const entryPoints = projectStructure?.entry_points || [];
  const targetFiles = inspectedFiles.length > 0 ? inspectedFiles : (entryPoints.slice(0, 3));

  const llmTasks = await generateLlmTasks(cleanPrompt, projectStructure);
  const tasks = llmTasks || fallbackTasks(cleanPrompt, targetFiles, configs);

  const plan = {
    id: planId,
    title: cleanPrompt.length > 55 ? cleanPrompt.substring(0, 52) + '...' : cleanPrompt,
    objective: cleanPrompt,
    configs,
    entryPoints,
    inspectedFiles: targetFiles,
    tasks,
    source: llmTasks ? 'model' : 'fallback',
    status: 'pending', // 'pending' | 'in_progress' | 'completed' | 'blocked' | 'failed' | 'cancelled'
    currentTaskId: null,
    startedAt: null,
    completedAt: null,
    elapsedSeconds: 0,
    filesModified: new Set(),
  };

  return plan;
}

/**
 * Asks the active model to decompose the request into ordered, verifiable
 * tasks. Returns null (caller falls back) on dispatch failure or malformed
 * output — planning must never block execution behind a broken model.
 */
async function generateLlmTasks(cleanPrompt, projectStructure) {
  let resp;
  try {
    // Dynamic import avoids a module-init cycle with agent.js
    const { dispatchAgentTurn } = await import('../components/agent.js');
    const repoContext = [
      projectStructure?.root_name ? `repo: ${projectStructure.root_name}` : null,
      projectStructure?.config_files?.length ? `configs: ${projectStructure.config_files.join(', ')}` : null,
      projectStructure?.entry_points?.length ? `entry points: ${projectStructure.entry_points.join(', ')}` : null,
      projectStructure?.tree ? `structure (truncated): ${JSON.stringify(projectStructure.tree).slice(0, 2500)}` : null,
    ].filter(Boolean).join('\n');

    const systemPrompt = `You are the task planner for Orbital X Agent. Decompose the user's request into a focused implementation plan.
Respond with ONLY a JSON object — no prose, no markdown fences — in exactly this shape:
{"title":"<short plan title>","tasks":[{"title":"<imperative task title>","objective":"<what to do and where>","files":["<relative/path>"],"criteria":"<verifiable acceptance criteria>","depends_on":[<1-based indices of earlier tasks this needs>]}]}
Rules:
- 2 to 6 tasks, proportional to real complexity. Never pad with generic phases.
- Each task must be independently executable by a coding agent with filesystem and shell tools.
- Order by dependency; depends_on must reference earlier tasks only.
- files: real paths from the repository context when known; omit the key otherwise.
- criteria must be objectively checkable (command exit codes, file contents, test results).`;

    const messages = [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: `REQUEST:\n${cleanPrompt}\n\nREPOSITORY CONTEXT:\n${repoContext || '(workspace not scanned)'}` },
    ];
    resp = await dispatchAgentTurn(messages, {});
  } catch (e) {
    console.warn('LLM planning dispatch failed, using fallback plan:', e);
    return null;
  }

  const parsed = extractJsonObject(resp?.content || '');
  if (!parsed || !Array.isArray(parsed.tasks) || parsed.tasks.length === 0) {
    console.warn('LLM plan was not parseable; falling back.', resp?.content?.slice(0, 200));
    return null;
  }

  // Normalize and hard-validate every task before it reaches the executor
  const tasks = parsed.tasks.slice(0, 12).map((t, i) => {
    const id = `task-${i + 1}`;
    const deps = Array.isArray(t.depends_on)
      ? t.depends_on.map(d => {
          const n = parseInt(d, 10);
          return Number.isInteger(n) && n >= 1 && n <= i ? `task-${n}` : null;
        }).filter(Boolean)
      : [];
    return {
      id,
      title: String(t.title || `Task ${i + 1}`).slice(0, 80),
      objective: String(t.objective || t.title || '').slice(0, 500),
      files: Array.isArray(t.files) ? t.files.filter(f => typeof f === 'string').slice(0, 6) : [],
      dependencies: [...new Set(deps)],
      status: 'pending',
      criteria: String(t.criteria || 'Change implemented and validate_changes reports no errors.').slice(0, 300),
      evidence: null,
      notes: null,
      retries: 0,
    };
  }).filter(t => t.objective.length > 0);

  return tasks.length > 0 ? tasks : null;
}

function extractJsonObject(text) {
  if (!text) return null;
  const fenced = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  const candidates = [fenced ? fenced[1] : null, text];
  for (const c of candidates) {
    if (!c) continue;
    const start = c.indexOf('{');
    const end = c.lastIndexOf('}');
    if (start === -1 || end <= start) continue;
    try {
      return JSON.parse(c.slice(start, end + 1));
    } catch (e) { /* try next candidate */ }
  }
  return null;
}

/**
 * Last-resort plan when the model cannot plan. Deliberately minimal and
 * honestly labelled — the executor reports it as a generic pass.
 */
function fallbackTasks(cleanPrompt, targetFiles, configs) {
  const hasCargo = configs.includes('Cargo.toml');
  const hasNode = configs.includes('package.json');
  const diagTool = hasCargo ? 'cargo check' : (hasNode ? 'node --check / tsc' : 'compiler diagnostic');

  return [
    {
      id: 'task-1',
      title: 'Inspect target area',
      objective: `Inspect the architecture, interfaces and dependencies relevant to "${cleanPrompt.substring(0, 60)}" (fallback plan: model planning was unavailable).`,
      files: targetFiles.slice(0, 2),
      dependencies: [],
      status: 'pending',
      criteria: 'Key file structures, imports, and data contracts inspected without assumptions.',
      evidence: null,
      notes: null,
      retries: 0,
    },
    {
      id: 'task-2',
      title: 'Implement the request',
      objective: `Implement the core changes requested in "${cleanPrompt.substring(0, 60)}".`,
      files: targetFiles.slice(0, 3),
      dependencies: ['task-1'],
      status: 'pending',
      criteria: 'Code written or patched into target modules adhering to existing project abstractions.',
      evidence: null,
      notes: null,
      retries: 0,
    },
    {
      id: 'task-3',
      title: 'Verify with project toolchain',
      objective: `Run ${diagTool} and validate that no regressions were introduced.`,
      files: targetFiles,
      dependencies: ['task-2'],
      status: 'pending',
      criteria: `${diagTool} passes with exit code 0; changes conform to the request.`,
      evidence: null,
      notes: null,
      retries: 0,
    },
  ];
}

/**
 * Checks if a task is eligible to run (dependencies completed and task is pending).
 */
export function canStartTask(task, plan) {
  if (!task || task.status !== 'pending') return false;
  if (!task.dependencies || task.dependencies.length === 0) return true;

  return task.dependencies.every(depId => {
    const depTask = plan.tasks.find(t => t.id === depId);
    return depTask && depTask.status === 'completed';
  });
}

/**
 * Returns the next eligible task in the plan.
 */
export function getNextTask(plan) {
  if (!plan || !plan.tasks) return null;
  return plan.tasks.find(t => canStartTask(t, plan)) || null;
}

/**
 * Validates and updates a task state in the active plan.
 * Enforces Gravitas Invariant 3: Cannot mark completed without evidence!
 */
export function updateTaskState(plan, taskId, newStatus, evidence = '', notes = '') {
  if (!plan || !plan.tasks) return { success: false, error: 'No active plan' };

  const task = plan.tasks.find(t => t.id === taskId);
  if (!task) return { success: false, error: `Task not found: ${taskId}` };

  const validStatuses = ['pending', 'in_progress', 'completed', 'blocked', 'failed', 'skipped', 'cancelled'];
  if (!validStatuses.includes(newStatus)) {
    return { success: false, error: `Invalid task status: ${newStatus}` };
  }

  // Invariant 3 enforcement
  if (newStatus === 'completed') {
    const cleanEv = (evidence || '').trim();
    if (cleanEv.length < 5) {
      return {
        success: false,
        error: 'Cannot mark task complete without verification evidence (Gravitas Invariant 3).'
      };
    }
    task.evidence = cleanEv;
  }

  task.status = newStatus;
  if (notes) task.notes = notes;

  // Update plan overall status
  const allCompleted = plan.tasks.every(t => t.status === 'completed' || t.status === 'skipped');
  const hasFailed = plan.tasks.some(t => t.status === 'failed');
  const hasBlocked = plan.tasks.some(t => t.status === 'blocked');

  if (allCompleted) {
    plan.status = 'completed';
    plan.completedAt = Date.now();
  } else if (hasFailed) {
    plan.status = 'failed';
  } else if (hasBlocked) {
    plan.status = 'blocked';
  } else if (plan.tasks.some(t => t.status === 'in_progress')) {
    plan.status = 'in_progress';
  }

  persistPlanState(plan);
  notify('orchestrator:task-updated', { plan, task });

  return { success: true, task, plan };
}

/**
 * Derives task completion progress fraction and percentage.
 */
export function calculateProgress(plan) {
  if (!plan || !plan.tasks || plan.tasks.length === 0) {
    return { completedCount: 0, totalCount: 0, percentage: 0 };
  }
  const totalCount = plan.tasks.length;
  const completedCount = plan.tasks.filter(t => t.status === 'completed' || t.status === 'skipped').length;
  const percentage = Math.round((completedCount / totalCount) * 100);

  return { completedCount, totalCount, percentage };
}

/**
 * Persists active plan to localStorage for workspace isolation.
 */
export function persistPlanState(plan) {
  try {
    const wsRoot = state.workspace.rootPath || 'default';
    const key = `orbital_active_plan_${encodeURIComponent(wsRoot)}`;

    if (!plan || plan.status === 'completed' || plan.status === 'cancelled') {
      localStorage.removeItem(key);
      state.orchestrator.activePlan = plan;
      return;
    }

    // Convert Set of filesModified to array for JSON serialization
    const serializablePlan = {
      ...plan,
      filesModified: Array.from(plan.filesModified || []),
    };

    localStorage.setItem(key, JSON.stringify(serializablePlan));
    state.orchestrator.activePlan = plan;
  } catch (err) {
    console.warn('Could not persist orchestrator plan:', err);
  }
}

/**
 * Restores persisted plan for the current workspace.
 */
export function restorePlanState() {
  try {
    const wsRoot = state.workspace.rootPath || 'default';
    const key = `orbital_active_plan_${encodeURIComponent(wsRoot)}`;
    const saved = localStorage.getItem(key);
    if (!saved) return null;

    const parsed = JSON.parse(saved);
    parsed.filesModified = new Set(parsed.filesModified || []);
    state.orchestrator.activePlan = parsed;
    return parsed;
  } catch (err) {
    console.warn('Could not restore orchestrator plan:', err);
    return null;
  }
}
